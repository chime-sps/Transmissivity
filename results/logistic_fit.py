import contextlib
import io
import warnings

import numpy as np
import matplotlib.pyplot as plt
import statsmodels.api as sm
from scipy.stats import norm


# Two location-scale link functions we support, used both for the *true*
# generative process (get_simulated_data) and for the *fit* (get_cross_point).
# Keeping one shared vocabulary ('logistic' / 'gaussian') for both lets any
# combination of true-vs-fit family be requested and compared.
_FIT_FAMILIES = {'logistic': sm.Logit, 'gaussian': sm.Probit}


def _family_cdf(x, family):
    """The 'logistic' or 'gaussian' CDF, evaluated at x."""
    if family == 'gaussian':
        return norm.cdf(x)
    elif family == 'logistic':
        return 1.0 / (1.0 + np.exp(-x))
    else:
        raise ValueError(f"family must be 'gaussian' or 'logistic', got {family!r}")


def _sigma_from_slope(slope, family):
    """
    Convert a 'slope' parameter (true or fit) into the actual standard
    deviation of the underlying distribution, in whatever units `slope`
    itself is defined in (log-S space, if logspace=True upstream).

    Both get_simulated_data and get_cross_point parameterize their curve as
    family_cdf(slope * (log(S) - log(cross_point))) -- i.e. the family's
    *standard* CDF evaluated at (log(S) - mu) / scale, with scale = 1/slope.
    For a Gaussian, that scale *is* the standard deviation. For a standard
    logistic distribution the variance is pi^2/3, so its standard deviation
    is scale * pi/sqrt(3) rather than scale itself.
    """
    scale = 1.0 / np.abs(slope)
    if family == 'gaussian':
        return scale
    elif family == 'logistic':
        return scale * np.pi / np.sqrt(3)
    else:
        raise ValueError(f"family must be 'gaussian' or 'logistic', got {family!r}")


def get_cross_point(X, y, logspace=True, family='logistic'):
    """
    family : 'logistic' (default) or 'gaussian' -- which link function to
    fit. Both are location-scale link functions with an S-shaped CDF, so
    the cross-point / standard-error / cdf_fit machinery below is identical
    either way -- only the link function (model.cdf) changes. Use
    'gaussian' when you believe the underlying turn-on is actually
    Gaussian, to avoid the systematic logistic-vs-Gaussian slope bias (see
    run_monte_carlo / compare_families).
    """
    if family not in _FIT_FAMILIES:
        raise ValueError(f"family must be one of {list(_FIT_FAMILIES)}, got {family!r}")

    # make sure that X and y are in 0/1 format even if sent in as booleans
    X = np.asarray(X, dtype=float)
    y = np.asarray(y, dtype=float)

    # allow for either log-spaced or linear-spaced fitting; default is log
    argX = np.log(X) if logspace else X
    exog = sm.add_constant(argX)

    model = _FIT_FAMILIES[family](y, exog)
    result = model.fit(disp=0)  # disp=0 silences the output

    b0, b1 = result.params
    cov = result.cov_params()
    intercept = np.exp(-b0 / b1) if logspace else -b0 / b1

    # du/db0 = -1/b1, du/db1 = b0/b1^2 (delta method for u = -b0/b1)
    var_intercept = (cov[0, 0] / b1**2
                      - 2 * b0 * cov[0, 1] / b1**3
                      + b0**2 * cov[1, 1] / b1**4)
    if logspace:
        # u = -b0/b1 = log(S50); propagate its SE through S50 = exp(u)
        # via d(exp(u))/du = exp(u) = S50 -- this was missing before, which
        # made se_intercept the SE of log(S50) rather than of S50 itself.
        se_intercept = intercept * np.sqrt(var_intercept)
    else:
        se_intercept = np.sqrt(var_intercept)

    if logspace:
        cdf_fit = lambda x: model.cdf(b0 + b1 * np.log(x))
    else:
        cdf_fit = lambda x: model.cdf(b0 + b1 * x)

    print(f'S = {intercept:.2f} +/- {se_intercept:.4f}')
    # `result` is returned too so callers (e.g. run_test) can build a
    # confidence band on the fitted curve via result.get_prediction(...).
    return intercept, se_intercept, cdf_fit, result


def get_simulated_data(n=3000,
                        S_min=1e-3,
                        S_max=10.0,
                        true_cross_point=2.0,
                        true_slope=4.0,
                        true_family='gaussian',
                        seed=0):
    """
    true_family : 'gaussian' (default, matches the original module) or
    'logistic' -- which distribution actually generates the detections.
    Pass this independently of get_cross_point's `family` to test how well
    a logistic (or Gaussian/probit) *fit* recovers data really generated by
    either process -- see run_monte_carlo / compare_families.
    """
    rng = np.random.default_rng(seed)
    log_S = rng.uniform(np.log(S_min), np.log(S_max), size=n)
    S = np.exp(log_S)

    linpred = true_slope * (np.log(S) - np.log(true_cross_point))
    p_detect = _family_cdf(linpred, true_family)

    y = rng.uniform(size=n) < p_detect

    return S, y, p_detect


def run_test(true_cross_point=5.0,
             true_slope=5.0,
             S_min=1e-3,
             S_max=10.0,
             logspace=True,
             true_family='gaussian',
             fit_family='logistic',
             plot=False,
             ):
    sim_S, sim_y, cdf_true = get_simulated_data(true_cross_point=true_cross_point,
                                                 true_slope=true_slope,
                                                 true_family=true_family,
                                                 S_min=S_min, S_max=S_max)

    cross_sim, se_sim, cdf_fit_sim, result = get_cross_point(sim_S, sim_y, logspace=logspace,
                                                               family=fit_family)
    b0, b1 = result.params
    se_b1 = result.bse[1]

    print('Cross point:')
    print(f'True: {true_cross_point:.2f} --> Fit: {cross_sim:.2f} +/- {se_sim:.2f}')
    print(f'Slope: True: {true_slope:.2f} --> Fit: {b1:.2f} +/- {se_b1:.2f}')

    if plot:
        fig, ax = plt.subplots(1, 1, figsize=(7, 5))

        # raw simulated points
        ax.plot(sim_S, sim_y, 'k.', alpha=0.08, label='simulated data')

        # smooth grid for the two curves + CI band
        S_grid = np.logspace(np.log10(S_min), np.log10(S_max), 400)

        # true turn-on curve (whichever family actually generated the data)
        true_curve = _family_cdf(true_slope * (np.log(S_grid) - np.log(true_cross_point)),
                                  true_family)
        ax.plot(S_grid, true_curve, color='tab:blue', lw=2, label=f'True {true_family} CDF')

        # fitted curve + its 95% confidence band (delta method via get_prediction)
        exog_grid = sm.add_constant(np.log(S_grid) if logspace else S_grid)
        pred = result.get_prediction(exog_grid).summary_frame(alpha=0.05)
        ax.plot(S_grid, pred['predicted'], color='tab:red', ls='--', lw=2,
                label=f'Fitted {fit_family} CDF')
        ax.fill_between(S_grid, pred['ci_lower'], pred['ci_upper'],
                         color='tab:red', alpha=0.2, label='95% CI (fit)')

        # cross-point markers, labeled so they show up in the legend
        ax.axvline(true_cross_point, color='tab:blue', ls=':', alpha=0.8,
                   label='True S$_{50}$')
        ax.axvline(cross_sim, color='tab:red', ls=':', alpha=0.8,
                   label='Fit S$_{50}$')

        # shaded regions showing the actual standard deviation (not just
        # 1/slope -- see _sigma_from_slope) of the true and fitted turn-on
        # transitions, in log-S space.
        sigma_true_log = _sigma_from_slope(true_slope, true_family)
        true_low = np.exp(np.log(true_cross_point) - sigma_true_log)
        true_high = np.exp(np.log(true_cross_point) + sigma_true_log)
        ax.axvspan(true_low, true_high, color='tab:blue', alpha=0.15,
                   label='True 1$\\sigma$ (transition width)')

        sigma_fit_log = _sigma_from_slope(b1, fit_family)
        if logspace:
            fit_low = np.exp(np.log(cross_sim) - sigma_fit_log)
            fit_high = np.exp(np.log(cross_sim) + sigma_fit_log)
        else:
            fit_low = cross_sim - sigma_fit_log
            fit_high = cross_sim + sigma_fit_log
        ax.axvspan(fit_low, fit_high, color='tab:red', alpha=0.15,
                   label='Fit 1$\\sigma$ (transition width)')

        ax.set_xscale('log')
        ax.set_xlabel('S')
        ax.set_ylabel('Detected? / P(detect)')
        ax.legend(loc='upper left', fontsize=8)

        plt.tight_layout()
        plt.show()

    return cross_sim, se_sim, b1, se_b1


def run_monte_carlo(N=300,
                     cross_point_range=(0.05, 5.0),
                     slope_range=(1.0, 10.0),
                     n_per_trial=1000,
                     S_min=1e-3,
                     S_max=10.0,
                     logspace=True,
                     true_family='gaussian',
                     fit_family='logistic',
                     seed=0,
                     plot=True,
                     verbose=False):
    """
    Monte Carlo test of get_cross_point.

    Draws N random (true_cross_point, true_slope) pairs -- true_cross_point
    log-uniform over `cross_point_range`, true_slope uniform over
    `slope_range` -- simulates a turn-on dataset generated by `true_family`
    ('gaussian' or 'logistic') for each pair via get_simulated_data, fits
    it with get_cross_point using `fit_family` ('logistic' or 'gaussian'),
    and compares the recovered parameters to the truth.

    `true_family` and `fit_family` are independent, so you can test e.g.
    how a logistic fit recovers Gaussian-generated data, or vice versa.
    Calling this with the same `seed`/N/ranges/n_per_trial reproduces the
    identical true_cross_point/true_slope draws across different family
    choices, so scenarios are directly comparable trial-by-trial (see
    compare_families, which sweeps all four true/fit combinations this
    way).

    Returns a dict of per-trial arrays (true/fit cross points and slopes,
    the fit's standard error, and derived True/Fit ratios) which is also
    what gets histogrammed when plot=True.
    """
    rng = np.random.default_rng(seed)

    true_cross_points = np.exp(rng.uniform(np.log(cross_point_range[0]),
                                            np.log(cross_point_range[1]), size=N))
    true_slopes = rng.uniform(slope_range[0], slope_range[1], size=N)

    fit_cross_points = np.full(N, np.nan)
    fit_se_cross = np.full(N, np.nan)
    fit_slopes = np.full(N, np.nan)

    # Sane bounds for a "real" cross point / slope, used below to catch
    # trials where the MLE didn't actually converge but statsmodels still
    # handed back some finite (often huge) garbage instead of raising --
    # this happens occasionally under near-complete separation (a very
    # steep true_slope combined with a cross point close to the edge of
    # [S_min, S_max]) and, left unfiltered, a single such trial can blow
    # up the mean/std of the whole batch and wreck the histograms.
    cross_bounds = (S_min * 1e-3, S_max * 1e3)
    slope_bound = 1e4

    n_nonconverged = 0
    n_outlier = 0

    for i in range(N):
        tcp = true_cross_points[i]
        tsl = true_slopes[i]
        sim_S, sim_y, _ = get_simulated_data(n=n_per_trial, S_min=S_min, S_max=S_max,
                                              true_cross_point=tcp, true_slope=tsl,
                                              true_family=true_family,
                                              seed=seed + i + 1)
        try:
            # get_cross_point prints a line every call, and statsmodels can
            # emit convergence/overflow warnings during optimization --
            # silence both for N trials rather than flooding the console.
            with contextlib.redirect_stdout(io.StringIO()), \
                 warnings.catch_warnings(record=True) as caught:
                warnings.simplefilter('always')
                cross_sim, se_sim, cdf_fit_sim, result = get_cross_point(
                    sim_S, sim_y, logspace=logspace, family=fit_family)

            converged = result.mle_retvals.get('converged', True)
            b1 = result.params[1]
            sane = (converged
                    and np.isfinite(cross_sim) and np.isfinite(se_sim) and np.isfinite(b1)
                    and cross_bounds[0] < cross_sim < cross_bounds[1]
                    and 0 < abs(b1) < slope_bound)

            if not sane:
                if not converged:
                    n_nonconverged += 1
                else:
                    n_outlier += 1
                if verbose:
                    msgs = '; '.join(str(w.message) for w in caught) or 'no warning captured'
                    print(f'Trial {i} (true_cross={tcp:.3f}, true_slope={tsl:.2f}) '
                          f'rejected: converged={converged}, cross={cross_sim:.3g}, '
                          f'b1={b1:.3g} ({msgs})')
                continue  # leave this trial as NaN

            fit_cross_points[i] = cross_sim
            fit_se_cross[i] = se_sim
            fit_slopes[i] = b1
        except Exception as e:
            if verbose:
                print(f'Trial {i} (true_cross={tcp:.3f}, true_slope={tsl:.2f}) failed: {e}')
            continue

    if n_nonconverged or n_outlier:
        print(f'Excluded {n_nonconverged} non-converged and {n_outlier} outlier/unstable '
              f'fits out of {N} trials (pass verbose=True for details).')

    # true/fit standard deviation of the transition, converted from each
    # side's own slope via its own family (see _sigma_from_slope -- a
    # logistic and a Gaussian with the same |slope| do NOT have the same
    # actual standard deviation).
    sigma_true = _sigma_from_slope(true_slopes, true_family)
    sigma_fit = _sigma_from_slope(fit_slopes, fit_family)

    ratio_cross = true_cross_points / fit_cross_points   # True/Fit cross point
    ratio_slope = true_slopes / fit_slopes                # True/Fit slope
    ratio_sigma = sigma_true / sigma_fit                  # True/Fit standard deviation
    # bonus diagnostic: is se_intercept correctly calibrated? if so this
    # "pull" should look like a standard normal (mean 0, std 1).
    pull_cross = (true_cross_points - fit_cross_points) / fit_se_cross

    n_failed = np.sum(np.isnan(fit_cross_points))
    if n_failed:
        print(f'{n_failed} / {N} trials failed to fit and were excluded.')

    results = dict(true_family=true_family,
                    fit_family=fit_family,
                    true_cross_points=true_cross_points,
                    true_slopes=true_slopes,
                    fit_cross_points=fit_cross_points,
                    fit_se_cross=fit_se_cross,
                    fit_slopes=fit_slopes,
                    ratio_cross=ratio_cross,
                    ratio_slope=ratio_slope,
                    ratio_sigma=ratio_sigma,
                    pull_cross=pull_cross)

    print(f'--- true = {true_family}, fit = {fit_family} ---')
    for name, arr in [('True/Fit cross point', ratio_cross),
                       ('True/Fit slope', ratio_slope),
                       ('True/Fit standard deviation', ratio_sigma)]:
        print(f'{name}: mean = {np.nanmean(arr):.3f}, std = {np.nanstd(arr):.3f}')

    if plot:
        _plot_monte_carlo_results(results)

    return results


def _hist_panel(ax, data, title, xlabel, ref_line, color='tab:gray',
                 emphasize=False):
    data = np.asarray(data)
    data = data[np.isfinite(data)]
    ax.hist(data, bins=30, color=color, alpha=0.75, edgecolor='0.3')
    ax.axvline(ref_line, color='k', ls='--', lw=1.5)
    mean, std = np.mean(data), np.std(data)
    ax.set_title(f'{title}\nmean = {mean:.3f}, std = {std:.3f}',
                 fontsize=11 if emphasize else 10,
                 fontweight='bold' if emphasize else 'normal')
    ax.set_xlabel(xlabel)
    ax.set_ylabel('count')


def _plot_monte_carlo_results(results):
    fig, axes = plt.subplots(2, 2, figsize=(11, 9))

    # emphasized panels (top row): the two ratios called out specifically
    _hist_panel(axes[0, 0], results['ratio_cross'],
                'True / Fit Cross Point', 'true S$_{50}$ / fit S$_{50}$',
                ref_line=1.0, color='tab:red', emphasize=True)
    _hist_panel(axes[0, 1], results['ratio_sigma'],
                'True / Fit Standard Deviation',
                'true $\\sigma$ / fit $\\sigma$',
                ref_line=1.0, color='tab:red', emphasize=True)

    # supplementary panels (bottom row)
    _hist_panel(axes[1, 0], results['ratio_slope'],
                'True / Fit Slope', 'true slope / fit slope',
                ref_line=1.0, color='tab:gray', emphasize=False)
    _hist_panel(axes[1, 1], results['pull_cross'],
                'Cross Point Pull (calibration check)',
                '(true $-$ fit) / se$_{fit}$',
                ref_line=0.0, color='tab:gray', emphasize=False)

    n = len(results['true_cross_points'])
    fig.suptitle(f'Monte Carlo recovery over {n} trials '
                 f'(true = {results.get("true_family", "?")}, '
                 f'fit = {results.get("fit_family", "?")})',
                 fontsize=13)
    plt.tight_layout()
    plt.show()


# The four true-vs-fit scenarios compare_families sweeps, in display order.
_SCENARIOS = [
    ('logistic', 'logistic'),
    ('gaussian', 'logistic'),
    ('logistic', 'gaussian'),
    ('gaussian', 'gaussian'),
]
_SCENARIO_COLORS = ['tab:blue', 'tab:orange', 'tab:green', 'tab:red']


def compare_families(N=300,
                      cross_point_range=(0.05, 5.0),
                      slope_range=(1.0, 10.0),
                      n_per_trial=1000,
                      S_min=1e-3,
                      S_max=10.0,
                      logspace=True,
                      seed=0,
                      plot=True,
                      verbose=False):
    """
    Runs run_monte_carlo across all four combinations of true/fit family:

        true=logistic, fit=logistic
        true=gaussian, fit=logistic
        true=logistic, fit=gaussian
        true=gaussian, fit=gaussian

    using the same seed/N/ranges/n_per_trial for each, so the
    true_cross_point/true_slope draws are identical across scenarios and
    only the generative shape (true_family) and/or fitted model
    (fit_family) differ -- results are directly comparable.

    Returns a dict keyed by (true_family, fit_family) -> run_monte_carlo's
    results dict for that scenario.
    """
    results_by_scenario = {}
    for true_family, fit_family in _SCENARIOS:
        results_by_scenario[(true_family, fit_family)] = run_monte_carlo(
            N=N, cross_point_range=cross_point_range, slope_range=slope_range,
            n_per_trial=n_per_trial, S_min=S_min, S_max=S_max, logspace=logspace,
            true_family=true_family, fit_family=fit_family,
            seed=seed, plot=False, verbose=verbose)

    if plot:
        _plot_scenario_comparison(results_by_scenario)

    return results_by_scenario


def _plot_scenario_comparison(results_by_scenario):
    fig, axes = plt.subplots(len(_SCENARIOS), 2, figsize=(11, 4 * len(_SCENARIOS)))

    for row, ((true_family, fit_family), color) in enumerate(zip(_SCENARIOS, _SCENARIO_COLORS)):
        res = results_by_scenario[(true_family, fit_family)]
        scenario_label = f'true={true_family}, fit={fit_family}'

        _hist_panel(axes[row, 0], res['ratio_cross'],
                    f'Cross Point ({scenario_label})',
                    'true S$_{50}$ / fit S$_{50}$',
                    ref_line=1.0, color=color, emphasize=True)
        _hist_panel(axes[row, 1], res['ratio_sigma'],
                    f'Standard Deviation ({scenario_label})',
                    'true $\\sigma$ / fit $\\sigma$',
                    ref_line=1.0, color=color, emphasize=True)

    n = len(next(iter(results_by_scenario.values()))['true_cross_points'])
    fig.suptitle(f'True/Fit recovery across 4 true-vs-fit scenarios ({n} trials each)',
                 fontsize=13)
    plt.tight_layout()
    plt.show()


